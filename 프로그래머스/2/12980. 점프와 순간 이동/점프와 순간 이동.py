def solution(N):
    ans = 1
    # 한번에 K칸을 점프하거나, 현재까지 온 거리 x 2에 해당하는 위치로의 순간이동을 할 수 있음
    # 순간이동은 건전지 소모 x, K칸 점프시 K만큼 건전지 사용
    
    # 아이언 수트를 착용했을땐, 순간이동이 더 효율적이다..
    # N만큼 이동하려고 할 떄, 
    # 5 > 4 > 2 > 1 (2)
    # 6 > 3 > 2 > 1 (2)
    while N > 1:
        if N % 2 == 0:
            N = N // 2
        else:
            N = N - 1
            ans += 1
    return ans